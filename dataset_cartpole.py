def generate_random_force(t_max, num_points=15):
    """Genera una forza casuale continua nel tempo usando spline cubiche"""
    t_random = np.linspace(0, t_max, num_points)
    F_random = np.random.uniform(-10, 10, num_points)
    F_random[0] = 0.0
    force_interp = interp1d(t_random, F_random, kind='cubic', fill_value="extrapolate")
    return force_interp

def cartpole_dynamics(t, state, force_func):
    """Calcola le derivate del sistema"""
    x, x_dot, theta, theta_dot = state
    F = force_func(t)

    A = np.array([
        [M + m, m * l * np.cos(theta)],
        [m * l * np.cos(theta), m * l**2]
    ])

    B = np.array([
        F - b * x_dot + m * l * theta_dot**2 * np.sin(theta),
        -c * theta_dot - m * g * l * np.sin(theta)
    ])

    accelerations = np.linalg.solve(A, B)
    x_ddot, theta_ddot = accelerations

    return [x_dot, x_ddot, theta_dot, theta_ddot]


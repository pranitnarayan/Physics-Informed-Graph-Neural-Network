def generate_step_force(t_max, step_duration=5.0):
    """Genera una forza costante a gradini che cambia ogni 'step_duration' secondi"""
    # Crea un vettore di tempi ogni 5 secondi: [0, 5, 10, 15, ..., 90]
    t_steps = np.arange(0, t_max + step_duration, step_duration)

    # Genera una forza casuale (tra -10 N e 10 N) per ciascun intervallo di 5 secondi
    F_values = np.random.uniform(-10, 10, len(t_steps))

    # Forza nulla nel primissimo intervallo per far partire il pendolo in caduta libera
    F_values[0] = 0.0

    # L'opzione kind='zero' mantiene il valore costante fino al tempo successivo (effetto gradino)
    force_interp = interp1d(t_steps, F_values, kind='zero', fill_value="extrapolate")
    return force_interp

def cartpole_dynamics(t, state, force_func):
    """Calcola le derivate del sistema"""
    x, x_dot, theta, theta_dot = state
    F = force_func(t)

